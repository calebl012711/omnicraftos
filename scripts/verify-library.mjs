import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const output = path.resolve(process.env.LIBRARY_OUTPUT || 'verification/library');
await fs.mkdir(output, { recursive: true });
const base = process.env.OMNICRAFT_URL || 'http://127.0.0.1:4173';
const report = { at: new Date().toISOString(), environment: 'Actual browser IndexedDB; OPFS failure injected at filesystem boundary', tests: {} };
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const timeout = setTimeout(() => browser.close(), 180000);
let page;
try {
  const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => { navigator.storage.getDirectory = async () => { throw new DOMException('Test filesystem unavailable', 'NotAllowedError'); }; });
  page = await context.newPage();
  await page.goto(base, { waitUntil: 'commit' });
  await page.getByTestId('nav-assets').click();
  const data = Buffer.from('OmniCraft OS library round trip\nKnown bytes: 0123456789\n');
  await page.getByLabel('Import library file', { exact: true }).setInputFiles({ name: 'library-roundtrip.txt', mimeType: 'text/plain', buffer: data });
  await page.getByTestId('status-bar-message').filter({ hasText: 'library-roundtrip.txt saved in this browser.' }).waitFor();
  let card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'library-roundtrip.txt', exact: true }) });
  await card.getByText('Saved in this browser', { exact: true }).waitFor();
  const id = (await card.getAttribute('data-testid')).replace('asset-card-', '');
  await page.reload();
  await page.getByTestId('nav-assets').click();
  card = page.getByTestId(`asset-card-${id}`);
  const [download] = await Promise.all([page.waitForEvent('download'), card.getByRole('button', { name: 'Download', exact: true }).click()]);
  const first = path.join(output, 'original.txt'); await download.saveAs(first);
  assert.deepEqual(await fs.readFile(first), data);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.locator('.mf-scroll-page').evaluate(element => element.scrollTop = 0);
  await page.screenshot({ path: path.join(output, 'files-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: path.join(output, 'files-desktop.png'), fullPage: true });
  await page.getByTestId('nav-projects').click();
  const [backup] = await Promise.all([page.waitForEvent('download'), page.getByTestId('export-backup-btn').click()]);
  const backupPath = path.join(output, 'backup.json'); await backup.saveAs(backupPath);
  const bundle = JSON.parse(await fs.readFile(backupPath, 'utf8'));
  const asset = bundle.assets.find(item => item.id === id);
  assert.equal(asset.opfsSynced, false, 'OPFS failure must not be recorded as a successful copy');
  assert.deepEqual(Buffer.from(asset.base64Bytes, 'base64'), data);
  report.tests.persistence = { passed: true, opfsUnavailable: true, realIndexedDBFallback: true, downloadBytesMatchAfterReload: true, backupBytesMatch: true, accurateOpfsState: true, mobileNoOverflow: true };
  await page.getByTestId('nav-assets').click();
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put = function (...args) { if (this.name === 'assets') throw new DOMException('Test library quota exceeded', 'QuotaExceededError'); return original.apply(this, args); };
  });
  await page.getByLabel('Import library file', { exact: true }).setInputFiles({ name: 'failed-import.txt', mimeType: 'text/plain', buffer: Buffer.from('Must not claim success') });
  await page.getByTestId('status-bar-message').filter({ hasText: 'File import failed:' }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'failed-import.txt', exact: true }).count(), 0);
  report.tests.failedImport = { passed: true, quotaErrorInjectedAtIndexedDBWrite: true, noSuccessCard: true, errorDisplayed: true };
  const second = await browser.newContext({ acceptDownloads: true });
  const restored = await second.newPage();
  await restored.goto(base, { waitUntil: 'commit' });
  await restored.getByTestId('nav-projects').click();
  await restored.getByText('Restore Backup', { exact: true }).locator('..').locator('input').setInputFiles(backupPath);
  await restored.getByTestId('status-bar-message').filter({ hasText: 'Restored' }).waitFor();
  await restored.getByTestId('nav-assets').click();
  const [restoredDownload] = await Promise.all([restored.waitForEvent('download'), restored.getByTestId(`asset-card-${id}`).getByRole('button', { name: 'Download', exact: true }).click()]);
  const final = path.join(output, 'restored.txt'); await restoredDownload.saveAs(final);
  assert.deepEqual(await fs.readFile(final), data);
  report.tests.restore = { passed: true, freshBrowserContext: true, downloadedBytesMatch: true };
  await restored.getByLabel('Import library file', { exact: true }).setInputFiles({ name: 'library-model.sc', mimeType: 'application/x-solidcraft', buffer: await fs.readFile('verification/model-minified-final/plate.sc') });
  const modelCard = restored.locator('article').filter({ has: restored.getByRole('heading', { name: 'library-model.sc', exact: true }) });
  await modelCard.getByRole('button', { name: 'Open in Model', exact: true }).click();
  await restored.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor({ timeout: 120000 });
  const measurement = await restored.frameLocator('iframe[title="Model geometry engine"]').locator('body').evaluate(() => window.solidcraft.execute('inspect.measure', {}));
  const expected = (100 * 60 - Math.PI * (11 * 11 + 4 * 2.5 * 2.5)) * 10;
  assert.ok(Math.abs(measurement.total.volume_mm3 - expected) / expected < .0001);
  report.tests.modelHandoff = { passed: true, nativeProjectTransferredFromLibrary: true, measuredVolumeMm3: measurement.total.volume_mm3 };
  report.passed = true;
} catch (error) { report.passed = false; report.error = String(error.stack || error); process.exitCode = 1; console.error(error); try { await page.screenshot({ path: path.join(output, 'failure.png') }); } catch {} }
finally { clearTimeout(timeout); await fs.writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); await browser.close(); }
