import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const out = path.resolve(process.env.MODEL_LIBRARY_OUTPUT || 'verification/model-library');
await fs.mkdir(out, { recursive: true });
const base = process.env.OMNICRAFT_URL || 'http://127.0.0.1:4173';
const report = { at: new Date().toISOString(), engine: 'Source-built SolidCraft release WASM through the suite UI', tests: {} };
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist'] });
const timeout = setTimeout(() => browser.close(), 480000);
let page;
try {
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(120000); page.on('dialog', dialog => dialog.accept());
  await page.goto(base, { waitUntil: 'commit' });
  await page.getByTestId('card-open-solidcraft').click();
  const newPart = page.getByRole('button', { name: 'New part', exact: true });
  await newPart.click();
  await page.getByRole('button', { name: 'Block', exact: true }).click();
  await page.getByLabel('New part name', { exact: true }).fill('Library verification block');
  await page.getByRole('button', { name: 'Create solid part', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Part created.' }).waitFor();
  const frame = page.frameLocator('iframe[title="Model geometry engine"]');
  const measure = () => frame.locator('body').evaluate(() => window.solidcraft.execute('inspect.measure', {}));
  const block = await measure();
  assert.ok(Math.abs(block.total.volume_mm3 - 80 * 60 * 8) < .1);
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Project saved' }).waitFor();
  await page.locator('.model-back').click();
  await page.getByTestId('nav-projects').click();
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Library verification block', exact: true }) });
  await card.getByText('Snapshot Stored', { exact: true }).waitFor();
  const id = (await card.getAttribute('data-testid')).replace('project-card-', '');
  const [backup] = await Promise.all([page.waitForEvent('download'), page.getByTestId('export-backup-btn').click()]);
  const backupPath = path.join(out, 'library-backup.json'); await backup.saveAs(backupPath);
  const bytes = JSON.parse(await fs.readFile(backupPath, 'utf8'));
  const snapshot = bytes.files.find(file => file.id === `model-snapshot-${id}`);
  assert.ok(snapshot && snapshot.base64Bytes, 'Backup contains the linked native snapshot');
  const native = Buffer.from(snapshot.base64Bytes, 'base64');
  assert.equal(native.subarray(0, 2).toString(), 'PK', 'Snapshot is a real native CAD archive');
  assert.ok(native.length > 100);
  await page.reload();
  await page.getByTestId('nav-projects').click();
  await page.getByTestId(`project-card-${id}`).getByRole('button', { name: 'Enter Model', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor();
  assert.ok(Math.abs((await measure()).total.volume_mm3 - block.total.volume_mm3) < .1);
  report.tests.library = { passed: true, saveThroughSuite: true, snapshotInBackup: true, reloadAndReopenThroughProjects: true, volumeMm3: block.total.volume_mm3 };
  await page.screenshot({ path: path.join(out, 'model-library.png') });
  await newPart.click();
  await page.getByRole('button', { name: 'Cylinder', exact: true }).click();
  await page.getByRole('button', { name: 'Create solid part', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Part created.' }).waitFor();
  const cylinder = await measure(), expected = Math.PI * 40 * 40 * 8;
  assert.ok(Math.abs(cylinder.total.volume_mm3 - expected) / expected < .0001);
  await page.getByRole('button', { name: 'top', exact: true }).click();
  await page.getByRole('button', { name: '3D', exact: true }).click();
  report.tests.starters = { passed: true, blockVolumeMm3: block.total.volume_mm3, cylinderVolumeMm3: cylinder.total.volume_mm3, expectedCylinderVolumeMm3: expected, cameraViewButtons: true };
  report.passed = true;
} catch (error) {
  report.passed = false; report.error = String(error.stack || error); process.exitCode = 1;
  try { report.body = (await page.locator('body').innerText()).slice(0, 5000); await page.screenshot({ path: path.join(out, 'failure.png') }); } catch {}
  console.error(error);
} finally { clearTimeout(timeout); await fs.writeFile(path.join(out, 'report.json'), JSON.stringify(report, null, 2)); await browser.close(); }
