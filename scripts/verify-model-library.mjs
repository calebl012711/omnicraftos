import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const out = path.resolve(process.env.MODEL_LIBRARY_OUTPUT || 'verification/model-library');
await fs.mkdir(out, { recursive: true });
const base = process.env.OMNICRAFT_URL || 'http://127.0.0.1:4173';
const report = { at: new Date().toISOString(), nativeApplicationLaunched: false, requestedSoftwareWebgl: process.env.OMNICRAFT_SOFTWARE_WEBGL === '1', engine: 'Source-built SolidCraft release WASM through the suite UI', tests: {} };
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist', ...(process.env.OMNICRAFT_SOFTWARE_WEBGL === '1' ? ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] : [])] });
const timeout = setTimeout(() => browser.close(), 480000);
let page;
try {
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(120000); page.on('dialog', dialog => dialog.accept());
  await page.goto(base, { waitUntil: 'commit' });
  await page.getByTestId('card-open-solidcraft').click();
  const newPart = page.getByRole('button', { name: 'New part', exact: true });
  await newPart.click();
  await page.getByRole('button', { name: 'Block', exact: true }).click();
  await page.getByLabel('New part name', { exact: true }).fill('Library verification block');
  await page.getByRole('button', { name: 'Create solid part', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Part created.' }).waitFor();
  const frame = page.frameLocator('iframe[title="Model geometry engine"]');
  const measure = () => frame.locator('body').evaluate(() => window.solidcraft.execute('inspect.measure', {}));
  const block = await measure();
  assert.ok(Math.abs(block.total.volume_mm3 - 80 * 60 * 8) < .1);
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Project saved' }).waitFor();
  await page.locator('.model-back').click();
  await page.getByTestId('nav-projects').click();
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Library verification block', exact: true }) });
  await card.getByText('Snapshot Stored', { exact: true }).waitFor();
  const id = (await card.getAttribute('data-testid')).replace('project-card-', '');
  const [backup] = await Promise.all([page.waitForEvent('download'), page.getByTestId('export-backup-btn').click()]);
  const backupPath = path.join(out, 'library-backup.json'); await backup.saveAs(backupPath);
  const bytes = JSON.parse(await fs.readFile(backupPath, 'utf8'));
  const snapshot = bytes.files.find(file => file.id === `model-snapshot-${id}`);
  assert.ok(snapshot && snapshot.base64Bytes, 'Backup contains the linked native snapshot');
  const native = Buffer.from(snapshot.base64Bytes, 'base64');
  assert.equal(native.subarray(0, 2).toString(), 'PK', 'Snapshot is a real native CAD archive');
  assert.ok(native.length > 100);
  await page.reload();
  await page.getByTestId('nav-projects').click();
  await page.getByTestId(`project-card-${id}`).getByRole('button', { name: 'Enter Model', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor();
  assert.ok(Math.abs((await measure()).total.volume_mm3 - block.total.volume_mm3) < .1);
  report.tests.library = { passed: true, saveThroughSuite: true, snapshotInBackup: true, reloadAndReopenThroughProjects: true, volumeMm3: block.total.volume_mm3 };
  await page.screenshot({ path: path.join(out, 'model-library.png') });
  await newPart.click();
  await page.getByRole('button', { name: 'Cylinder', exact: true }).click();
  await page.getByRole('button', { name: 'Create solid part', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Part created.' }).waitFor();
  const cylinder = await measure(), expected = Math.PI * 40 * 40 * 8;
  assert.ok(Math.abs(cylinder.total.volume_mm3 - expected) / expected < .0001);
  await page.getByRole('button', { name: 'top', exact: true }).click();
  await page.getByRole('button', { name: '3D', exact: true }).click();
  report.tests.starters = { passed: true, blockVolumeMm3: block.total.volume_mm3, cylinderVolumeMm3: cylinder.total.volume_mm3, expectedCylinderVolumeMm3: expected, cameraViewButtons: true };
  // Open the saved part, then use the real upstream document-tab commands.
  await page.locator('.model-back').click();
  await page.getByTestId('nav-projects').click();
  await page.getByTestId(`project-card-${id}`).getByRole('button', { name: 'Enter Model', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor();
  await page.getByRole('button', { name: 'Full CAD workspace', exact: true }).click();
  await page.waitForFunction(() => { const button = document.querySelector('.model-native-hostbar button:last-child'); return button && !button.disabled; });
  const originalTab = await frame.locator('body').evaluate(async () => (await window.solidcraft.request('ui.documents', {})).active);
  await frame.locator('body').evaluate(async () => {
    const api = window.solidcraft;
    await api.request('ui.documents', { action: 'new' });
    await api.execute('file.new', { name: 'Native tab safety part' });
    await api.execute('solid.box', { length: 10, width: 20, height: 30 });
  });
  assert.ok(Math.abs((await measure()).total.volume_mm3 - 6000) < .1);
  await page.getByRole('button', { name: 'Save to Projects', exact: true }).click();
  await page.locator('.model-native-hostbar [role="status"]').filter({ hasText: /Native tab safety part.*Saved in engine/ }).waitFor();
  const unsafeTab = await frame.locator('body').evaluate(async index => {
    const api = window.solidcraft;
    await api.request('ui.documents', { action: 'new' });
    await api.execute('file.new', { name: 'Unsaved secondary design' });
    await api.execute('solid.box', { length: 2, width: 3, height: 4 });
    const tabs = await api.request('ui.documents', {});
    await api.request('ui.documents', { action: 'switch', index });
    return { index: tabs.active, count: tabs.documents.length };
  }, originalTab);
  await page.getByRole('button', { name: 'Guided workspace', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Save or close other unsaved designs' }).waitFor();
  assert.equal(await frame.locator('body').evaluate(async () => (await window.solidcraft.request('ui.documents', {})).documents.length), unsafeTab.count);
  await frame.locator('body').evaluate(async index => { await window.solidcraft.request('ui.documents', { action: 'close', index, force: true }); }, unsafeTab.index);
  await page.locator('.model-back').click();
  await page.getByTestId('nav-projects').click();
  const second = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Native tab safety part', exact: true }) });
  await second.getByText('Snapshot Stored', { exact: true }).waitFor();
  const secondId = (await second.getAttribute('data-testid')).replace('project-card-', '');
  assert.notEqual(secondId, id, 'A new upstream document must not overwrite the previous library project');
  const [secondBackup] = await Promise.all([page.waitForEvent('download'), page.getByTestId('export-backup-btn').click()]);
  const secondBackupPath = path.join(out, 'native-tab-backup.json'); await secondBackup.saveAs(secondBackupPath);
  const saved = JSON.parse(await fs.readFile(secondBackupPath, 'utf8'));
  assert.equal(saved.files.find(file => file.id === `model-snapshot-${id}`).base64Bytes, snapshot.base64Bytes, 'The original native snapshot must stay byte-identical');
  assert.ok(saved.files.some(file => file.id === `model-snapshot-${secondId}`));
  await second.getByRole('button', { name: 'Enter Model', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor();
  assert.ok(Math.abs((await measure()).total.volume_mm3 - 6000) < .1);
  await frame.locator('body').evaluate(() => window.solidcraft.execute('parameters.add', { name: 'save_integrity_marker', expression: '7', unit: 'mm' }));
  const nameBeforeSave = await frame.locator('body').evaluate(async () => (await window.solidcraft.inspect()).name);
  await page.getByRole('button', { name: 'Save project', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Project saved' }).waitFor();
  assert.equal(await frame.locator('body').evaluate(async () => (await window.solidcraft.inspect()).name), nameBeforeSave, 'Saving a reopened design must preserve its name');
  await page.reload();
  await page.getByTestId('nav-projects').click();
  await page.getByTestId(`project-card-${secondId}`).getByRole('button', { name: 'Enter Model', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Native project reopened' }).waitFor();
  const marker = await frame.locator('body').evaluate(async () => (await window.solidcraft.inspect()).params.find(param => param.name === 'save_integrity_marker'));
  assert.equal(marker?.expression, '7', 'The updated native snapshot must include the latest write, not the previous file');
  assert.equal(marker?.unit, 'mm');
  report.tests.upstreamDocuments = { passed: true, separateProjectIds: true, originalSnapshotUnchanged: true, newNativePartReopened: true, unsavedSecondaryTabPreserved: true, reopenedNamePreserved: true, updatedSnapshotSurvivedReload: true, nativeApplicationLaunched: false };
  report.passed = true;
} catch (error) {
  report.passed = false; report.error = String(error.stack || error); process.exitCode = 1;
  try { report.body = (await page.locator('body').innerText()).slice(0, 5000); await page.screenshot({ path: path.join(out, 'failure.png') }); } catch {}
  console.error(error);
} finally { clearTimeout(timeout); await fs.writeFile(path.join(out, 'report.json'), JSON.stringify(report, null, 2)); await browser.close(); }
